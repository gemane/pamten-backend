_US_STATE_NAMES = {v.casefold(): v for v in _US_STATES.values()}

# The CURATED half of the map: jurisdictions where GLEIF lists several
# registers and the general corporate register must be picked by hand over the
# sector registries (insurance, credit unions, charities, trust companies).
# Verified against the 2024-11-20 RA list; extend only with the same check.
_PLACE_OVERRIDES = {
    ("US", "illinois"):   "RA000608",  # Business Services, not the License List
    ("US", "new york"):   "RA000628",  # Corporation Database, not insurance/charities
    ("US", "texas"):      "RA000637",  # Corporations Section, not credit unions/trusts
    ("US", "washington"): "RA000641",  # Corporations Division, not Business Lookup
}


# Countries whose jurisdiction scheme has been AUDITED for this map. The
# exactly-one rule alone is a trap: Bavaria's only listed register is a
# Foundations Directory, so a German PSC saying "Bavaria" plus an HRB number
# would mint a register_id on a sector registry that never issued it. A
# country joins this set only after checking that its listed jurisdictions
# are general corporate registers (US: 52 jurisdictions, all Secretary-of-
# State-class, 4 needing the overrides above).
_PLACE_COUNTRIES = {"US"}


@functools.lru_cache(maxsize=1)
def _place_registers() -> dict:
    """(country ISO-2, jurisdiction casefolded) → RA code — exactly-one, audited
    countries only."""
    counts: dict = {}
    for code, entry in _load("gleif_ra.json").items():
        if not isinstance(entry, dict):
            continue  # stale flat bundle — map stays empty, feature degrades off
        for country in entry.get("countries") or []:
            if country not in _PLACE_COUNTRIES:
                continue
            for jur in entry.get("jurisdictions") or []:
                counts.setdefault((country, jur.casefold()), []).append(code)
    return {key: codes[0] for key, codes in counts.items() if len(codes) == 1}


def register_for_place(iso2: str | None, place: str | None) -> str | None:
    """A sub-national place name → its RA code, where that is unambiguous.

    The place-level counterpart of `sole_register_for_country`: "USA" names 64
    registers, but "Delaware" names exactly one — so a source stating the
    STATE can contribute a register_id even though the country never could.
    Accepts the forms sources actually use: the jurisdiction name ("Delaware"),
    "State of X", a trailing country ("Delaware, USA"), or a USPS abbreviation
    ("DE", the OpenCorporates us_de form). A recognised US state name implies
    the country when the caller could not resolve one — "Delaware" in a PSC's
    country_registered field IS the country statement. Curated overrides pick
    the general corporate register for the four states where GLEIF lists
    sector registries beside it; everything else must be exactly-one.
    """
    norm = " ".join((place or "").replace(",", " ").split())
    if not norm:
        return None
    low = norm.casefold()
    for prefix in ("state of ", "the state of "):
        if low.startswith(prefix):
            low = low[len(prefix):]
    for suffix in (" usa", " united states", " united states of america", " us"):
        if low.endswith(suffix):
            low = low[: -len(suffix)].strip()
    if len(low) == 2 and low.upper() in _US_STATES:
        low = _US_STATES[low.upper()].casefold()
    country = (iso2 or "").strip().upper() or None
    if country is None and low in _US_STATE_NAMES:
        country = "US"
    if country is None:
        return None
    hit = (_PLACE_OVERRIDES.get((country, low))
           or _place_registers().get((country, low)))
    if hit or country != "US":
        return hit
    # "Delaware Division Of Corporations", "Sunbiz Florida", "Delaware
    # Secretary Of State": the state's name inside the filer's words, when
    # exactly one state is named.
    padded = f" {low} "
    named = [st for st in _US_STATE_NAMES if f" {st} " in padded]
    if len(named) == 1:
        return _PLACE_OVERRIDES.get((country, named[0])) or _place_registers().get((country, named[0]))
    return None


#: Registers a NUMBER FORMAT identifies where the country alone names several.
#: Japan lists four RAs, but GLEIF itself files the Legal Affairs Bureau company
#: registration number (会社法人等番号, "0104-01-056795") under RA000412 and the
#: 13-digit corporate number (法人番号) under RA001075 — audited on the dev graph:
#: every dashed number sits under RA000412, none elsewhere. SoftBank Group's PSC
#: record carried that dashed number and stayed a name-only twin of its LEI node.
#: (country, format, RA code, canonical form of a matching number). Switzerland
#: likewise lists four RAs; a `CHE-105.909.036` UID is the Commercial Register's
#: form — all 24 Swiss GLEIF nodes on dev carry exactly that shape under
#: RA000549. Filers write the prefix as "Che-", GLEIF as "CHE-": uppercase it.
_NUMBER_FORMAT_REGISTERS = (
    ("JP", re.compile(r"\d{4}-\d{2}-\d{6}"), "RA000412", None),
    ("CH", re.compile(r"CHE-\d{3}\.\d{3}\.\d{3}", re.IGNORECASE), "RA000549", str.upper),
)


def register_for_number_format(iso2: str | None, number: str | None) -> str | None:
    """The RA code a registration number's FORMAT names, where audited.

    The third way to a `register_id` beside the sole-register country and the
    place map: for countries whose registers issue distinguishable formats, the
    number itself says which register issued it. Whitespace-insensitive like
    `make_register_id`; the format must match the whole number.
    """
    rule = _number_format_rule(iso2, number)
    return rule[2] if rule else None


def canonical_register_number(iso2: str | None, number: str | None) -> str | None:
    """The number as the register writes it, when a format rule matched — else
    the number unchanged. `make_register_id` preserves case on purpose (it is
    significant in some registers); a format rule knows its own register's
    spelling, so "Che-105.909.036" becomes the "CHE-105.909.036" GLEIF carries."""
    rule = _number_format_rule(iso2, number)
    if rule and rule[3]:
        return rule[3]("".join((number or "").split()))
    return number


def _number_format_rule(iso2: str | None, number: str | None):
    country = (iso2 or "").strip().upper()
    compact = "".join((number or "").split())
    if not country or not compact:
        return None
    for rule in _NUMBER_FORMAT_REGISTERS:
        if rule[0] == country and rule[1].fullmatch(compact):
            return rule
    return None


#: Words that name no register on their own — "Commercial Register" is what
#: 176 German courts are called. A match must carry at least one other word.
_GENERIC_WORDS = frozenset(
    "register registry registrar registration registers commercial company companies "
    "business trade enterprise enterprises office authority national central state "
    "public general court local federal ministry department division of the and for "
    "de du des la le les für der die das van het en et y e a".split())


def _singular(token: str) -> str:
    """companies → company, registries → registry, societes → societe: a filer's
    plural and the list's singular are the same word."""
    if len(token) > 4 and token.endswith("ies"):
        return token[:-3] + "y"
    if len(token) > 4 and token.endswith("s") and not token.endswith("ss"):
        return token[:-1]
    return token


#: Connectives that "Securities & Investments Commission" and "Securities and
#: Investments Commission" differ by — dropped before names are compared.
_STOP_WORDS = frozenset("and the of for de du des la le les et en van het und der die das y e a".split())


def _name_tokens(text: str | None) -> frozenset:
    folded = unicodedata.normalize("NFKD", text or "").encode("ascii", "ignore").decode()
    return frozenset(_singular(t) for t in re.split(r"[^a-z0-9]+", folded.casefold())
                     if t and t not in _STOP_WORDS)


#: What filers write that GLEIF's list does not: abbreviations and the name of
#: an organisation that runs several registers, resolved to the register a
#: company (a PSC controller) is on. From a survey of the 87,057 foreign
#: corporate controllers in the 2026-09 PSC snapshot; each line cites the
#: phrasing that needed it.
_REGISTER_ALIASES = {
    ("JE", "jfsc"): "RA000414",                    # "Jfsc Companies Registry" (1,091)
    ("JE", "jersey registry"): "RA000414",         # (150)
    ("JE", "jersey financial services commission"): "RA000414",   # (700) — also names the funds list
    ("GG", "guernsey registry"): "RA000383",       # (857) runs four registers; companies is the one
    ("GG", "guernsey register"): "RA000383",       # (114)
    ("GG", "guernsey companies registry"): "RA000383",   # (84)
    ("HK", "registrar of companies"): "RA000388",  # "Registrar Of Companies Hong Kong" (22)
    ("AU", "asic"): "RA000014",                    # (169) runs the companies and the licensees registers
    ("AU", "australian securities and investments commission"): "RA000014",   # (295 + variants)
    ("FR", "rcs"): "RA000192",                     # "Rcs Paris" (97), "Rcs Nanterre" (73); folds to Sirene
    ("LU", "rcs"): "RA000432",                     # "Rcs Luxembourg" (39)
    ("IE", "cro"): "RA000402",                     # (142)
    ("SE", "bolagsverket"): "RA000544",
    ("NL", "kvk"): "RA000463",
}


@functools.lru_cache(maxsize=1)
def _register_names() -> dict:
    """country → [(code, name-token-set, is_site)] for every register name and
    site domain in the bundle — the vocabulary `register_for_name` matches."""
    out: dict = {}
    for code, entry in _load("gleif_ra.json").items():
        if not isinstance(entry, dict):
            continue
        aliases = [(_name_tokens(n), "name") for n in entry.get("names") or [entry.get("name") or ""]]
        site = entry.get("site")
        if site:
            aliases.append((_name_tokens(site.split(".")[0]), "site"))   # "kvk" of kvk.nl
        for country in entry.get("countries") or []:
            out.setdefault(country, []).extend((code, toks, kind) for toks, kind in aliases if toks)
    for (country, alias), code in _REGISTER_ALIASES.items():
        out.setdefault(country, []).append((code, _name_tokens(alias), "alias"))
    return out


@functools.lru_cache(maxsize=None)
def _country_words(iso2: str) -> frozenset:
    from app.scraper.bulk_import import _ISO2_COUNTRY
    words = set(_name_tokens(_ISO2_COUNTRY.get(iso2, ""))) | {iso2.lower()}
    words |= {_singular(w) for w in _DEMONYMS.get(iso2, ())}
    return frozenset(words)


