def register_for_name(iso2: str | None, text: str | None) -> str | None:
    """The register a filer NAMED, where exactly one of the country's registers
    fits the words — the first thing to try, before any guess by country.

    A PSC record's `place_registered` / `legal_authority` is free text, but it
    usually is the register's name in the filer's language: "Kamer van
    Koophandel", "Firmenbuch", "Registre de Commerce et des Sociétés", "CSSF".
    GLEIF's list carries every register's international and local names, its
    organisation's names and its site, so the words can be matched — and this
    keys funds as well as companies, since a filer naming the CSSF gets the
    CSSF register. Matching, accent- and case-folded, by word sets:
    the whole name (best), the register's name inside the text, or the text
    inside the name (an abbreviation — "CSSF" in "CSSF - Supervised Entities").
    Generic words alone ("Commercial Register" — 176 German courts) never
    match, and two registers fitting equally well means no answer.
    """
    country = (iso2 or "").strip().upper()
    tokens = _name_tokens(text)
    if not country or not tokens:
        return None
    # "Netherlands", "Swiss", "Irish Law": the country's own name names no
    # register, and must not ride along as a match of "The Netherlands Chamber
    # of Commerce". Only country words (plus "law" and the like) → no answer;
    # the specific remainder is what an abbreviation match must rest on.
    specific = tokens - _GENERIC_WORDS - _country_words(country) - _NOISE_WORDS
    scores: dict[str, int] = {}
    for code, alias, kind in _register_names().get(country, ()):
        if alias == tokens:
            score = 4 if kind == "alias" else 3      # a curated alias is deliberate: it wins a tie
        elif alias <= tokens and kind != "site":
            score = 2                                # the register's name inside the filer's words
        elif tokens <= alias and specific:
            score = 1                                # an abbreviation or a part of the name
        else:
            continue
        scores[code] = max(scores.get(code, 0), score)
    if not scores:
        return None
    best = max(scores.values())
    winners = [c for c, sc in scores.items() if sc == best]
    if len(winners) == 1:
        return winners[0]
    # One organisation, several registers — Ireland's Companies Registration
    # Office runs the companies register and the friendly-societies one. The
    # filer means the register the country's companies are on, when the
    # audit knows which that is.
    general = general_register_for_country(country)
    return general if general in winners else None


@functools.lru_cache(maxsize=1)
def _general_registers() -> dict:
    """country ISO-2 → the register GLEIF's own GENERAL entities sit on nearly
    every time, from `general_registers.json` (see `register_audit`). Absent
    file or a stale shape → empty map; the feature degrades to the other rules."""
    try:
        data = _load("general_registers.json")
    except Exception:  # noqa: BLE001 - data file optional
        return {}
    countries = data.get("countries") if isinstance(data, dict) else None
    return {c: e["code"] for c, e in (countries or {}).items()
            if isinstance(e, dict) and e.get("code")}


def general_register_for_country(iso2: str | None) -> str | None:
    """The country's general corporate register, where the audit found one.

    The last resort after the sole-register rule, the place map and the
    number-format rules: the RA table lists four registers for the
    Netherlands, but 100% of Dutch GENERAL entities on GLEIF sit on the KVK
    (RA000463) — the other three are sector registries a company would never
    file a PSC number from. Countries where no register clearly dominates
    (Germany per court, the US and Canada per state) are not in the map.
    """
    return _general_registers().get(iso2.strip().upper()) if iso2 else None


@functools.lru_cache(maxsize=1)
def _zero_insensitive_ras() -> frozenset:
    """The audited US state registers, where a purely numeric filing number's
    leading zeros are formatting, not identity: GLEIF publishes Tesla's Texas
    number as 0805587591, the Companies House filer wrote 805587591, and both
    name the same registration. Exactly the place-map scope — the same audit
    that vouched for the registers vouches for their numbering."""
    return frozenset(_place_registers().values()) | frozenset(_PLACE_OVERRIDES.values())


def make_register_id(code: str | None, number: str | None) -> str | None:
    """(RA code, register number) → the `register_id` hard identifier, or None.

    Conservative on purpose — a missing key is safe, a wrong merge key is not:
    - both parts required; the placeholder codes above never qualify;
    - the code is uppercased (it is an enum);
    - ALL whitespace is removed from the number ("HRB 12345" and "HRB12345" are
      the same registration), but case and leading zeros are preserved — both
      are significant in some registers (Swiss numbers are zero-padded) — EXCEPT
      for the audited US state registers, where sources demonstrably disagree
      on zero-padding of what is a plain integer (see _zero_insensitive_ras).
    """
    ra = (code or "").strip().upper()
    num = "".join((number or "").split())
    if not ra or not num or ra in _EXCLUDED_RA:
        return None
    if num.isdigit() and ra in _zero_insensitive_ras():
        num = num.lstrip("0") or "0"
    ra = _REGISTER_FOLDS.get(ra, ra)
    style = _NUMBER_STYLES.get(ra)
    if style:
        num = style(num)
    return f"{ra}:{num}"


def _swiss_uid(num: str) -> str:
    """CHE105909036 / Che-105.909.036 → CHE-105.909.036, the UID's official form."""
    m = re.fullmatch(r"(?i)CHE[-‑]?(\d{3})\.?(\d{3})\.?(\d{3})", num)
    return f"CHE-{m.group(1)}.{m.group(2)}.{m.group(3)}" if m else num


def _digits_only(num: str) -> str:
    """0402.231.383 → 0402231383: separators are typography, not identity."""
    return num.replace(".", "") if re.fullmatch(r"[\d.]+", num) else num


#: Registers that carry ONE national number under two codes — audited on the
#: full golden copy (2026-09-20): the Swiss UID sits under the UID register
#: (RA000548, 55%) and the Commercial Register (RA000549, 45%), written
#: CHE105909036 and CHE-105.909.036; the French SIREN under Sirene (RA000189,
#: 95%) and the RCS (RA000192, 5%). Two keys for one number is no key at all,
#: so both fold to one code — the Commercial Register for Switzerland (the
#: register of record; what every earlier node carries), Sirene for France.
_REGISTER_FOLDS = {"RA000548": "RA000549", "RA000192": "RA000189"}

#: One spelling per register where GLEIF itself uses several for one number.
_NUMBER_STYLES = {
    "RA000549": _swiss_uid,          # Swiss UID
    "RA000189": _digits_only,        # SIREN, occasionally "542 014 428"
    "RA000025": _digits_only,        # Belgian KBO: 0402.231.383 and 0402231383
}
