"""Industry classification — what a company DOES, in one tree.

Owlgraph shows every company's sector in **NACE Rev. 2** (Eurostat's
statistical classification of economic activities: section > division >
group > class, e.g. C > 23 > 23.3 > 23.32 "Manufacture of bricks, tiles and
construction products, in baked clay"), and keeps beside it what each source
actually said, in the source's own scheme:

- **US SIC** — the code EDGAR assigns every filer (`sic` / `sicDescription` in
  the submissions document; public domain). Reaches NACE through the US
  Census crosswalks (SIC → NAICS → ISIC) and the UN's ISIC → NACE table, a
  chain of one-to-many steps, so it lands at the deepest NACE node holding
  a majority of its paths: a class for a tightly defined industry, a bare
  section for a catch-all like 7370 "computer programming, data processing".
- **UK SIC 2007** — the codes Companies House holds for every UK company
  (up to four, the first being the principal activity; OGL). A UK subclass IS
  a NACE class with a fifth digit, so 23320 → 23.32 exactly; three UK-only
  codes (dormant, non-trading, residents' management) map to nothing.

The mapping lives in a bundle regenerated by `scripts/build_industry_bundle.py`
(`app/scraper/data/industry_nace.json`: the NACE tree with EN and DE labels,
each scheme's codes with their titles and NACE node).

Storage: one `IndustryCode` vertex per (entity, scheme, position) — the
statement as the source made it, with its provenance:

    (:IndustryCode {key, entity_id, scheme: 'uk-sic', code: '23320', label,
                    position: 1, nace_code: '23.32', source_id, source_url,
                    source_date, first_seen_at, last_seen_at})

and on the Entity itself `nace_code`, the node the panel draws the tree from:
the principal statement of the most exact scheme (a register's native NACE
code over a crosswalked SIC). `profile_for` returns the tree and the
statements for the full profile; `migrate` follows an entity merge.
"""
import hashlib
import json
import logging
import re
from datetime import datetime, timezone
from functools import lru_cache
from pathlib import Path

log = logging.getLogger(__name__)

TYPE = "IndustryCode"
_BUNDLE = Path(__file__).parent / "scraper" / "data" / "industry_nace.json"

#: Schemes in order of exactness: the first one an entity has a statement in
#: decides its `nace_code`. UK SIC is NACE with a fifth digit; US SIC reaches
#: NACE through a lossy crosswalk.
SCHEME_PRECEDENCE = ("uk-sic", "us-sic")

#: The languages the bundle carries labels in (Eurostat publishes EN/FR/DE).
LABEL_LANGS = ("en", "de")


@lru_cache(maxsize=1)
def bundle() -> dict:
    return json.loads(_BUNDLE.read_text(encoding="utf-8"))


def scheme_name(scheme: str) -> str | None:
    s = bundle()["schemes"].get(scheme)
    return s["name"] if s else None


def code_entry(scheme: str, code: str | None) -> dict | None:
    """The bundle's row for a source code: {"label", "nace"} — None when unknown."""
    if not code:
        return None
    return (bundle()["schemes"].get(scheme) or {}).get("codes", {}).get(code)


def nace_for(scheme: str, code: str | None) -> str | None:
    """The NACE node a source code maps to, or None (unknown code, or one
    that means nothing in NACE)."""
    entry = code_entry(scheme, code)
    return entry.get("nace") if entry else None


def nace_node(code: str | None) -> dict | None:
    return bundle()["nace"].get(code) if code else None


def nace_tree(code: str | None) -> list[dict]:
    """The path from the section down to `code`, each step
    {level, code, label: {en, de}} — empty for an unknown code."""
    out: list[dict] = []
    node = nace_node(code)
    while node and code:
        out.append({"level": node["level"], "code": code, "label": node["label"]})
        code = node.get("parent")
        node = nace_node(code)
    return list(reversed(out))


# ── Source statements ───────────────────────────────────────────────────────

_UK_SIC_TEXT = re.compile(r"^\s*(\d{5})\s*-\s*(.*?)\s*$")


def parse_uk_sic(text: str | None) -> tuple[str, str] | None:
    """Companies House's `SICCode.SicText_n` cell — "23320 - Manufacture of
    bricks, tiles and construction products, in baked clay" — as (code,
    label). None for an empty or malformed cell; "None Supplied" is one."""
    m = _UK_SIC_TEXT.match(text or "")
    return (m.group(1), m.group(2)) if m else None


def us_sic_from_submissions(submissions: dict | None) -> tuple[str, str] | None:
    """(code, title) from EDGAR's submissions document, or None when the filer
    has none (a person, a trust with no activity). The title is the SEC's own
    `sicDescription`, falling back to the bundle's list."""
    if not submissions:
        return None
    code = str(submissions.get("sic") or "").strip()
    if not code.isdigit():
        return None
    code = code.zfill(4)
    label = (submissions.get("sicDescription") or "").strip()
    if not label:
        entry = code_entry("us-sic", code)
        label = entry["label"] if entry else ""
    return code, label


def statement_key(entity_id: str, scheme: str, position: int) -> str:
    return hashlib.sha1(f"{entity_id}|{scheme}|{position}".encode()).hexdigest()


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def statement_props(entity_id: str, scheme: str, code: str, label: str | None, *,
                    source_id: str, source_url: str | None = None,
                    source_date: str | None = None, position: int = 1) -> dict:
    """The property bag of one statement, ready to UPSERT on `key`."""
    return {
        "key": statement_key(entity_id, scheme, position),
        "entity_id": entity_id,
        "scheme": scheme,
        "code": code,
        "label": label or (code_entry(scheme, code) or {}).get("label"),
        "position": position,
        "nace_code": nace_for(scheme, code),
        "source_id": source_id,
        "source_url": source_url,
        "source_date": source_date,
        "last_seen_at": _now(),
    }


def upsert_sql(props: dict) -> str:
    sets = ", ".join(f"{name} = :{name}" for name in props)
    return (f"UPDATE {TYPE} SET {sets}, first_seen_at = COALESCE(first_seen_at, :last_seen_at) "
            f"UPSERT WHERE key = :key")


def record(entity_id: str, scheme: str, code: str, label: str | None, *,
           source_id: str, source_url: str | None = None, source_date: str | None = None,
           position: int = 1, stamp: bool = True) -> dict | None:
    """Write one statement and (by default) re-derive the entity's `nace_code`.
    Best-effort like `record_claim`: a scrape must not fail over its sector."""
    from app.db.arcadedb import run_sql
    if not (entity_id and scheme and code and source_id):
        return None
    props = statement_props(entity_id, scheme, code, label, source_id=source_id,
                            source_url=source_url, source_date=source_date, position=position)
    try:
        run_sql(upsert_sql(props), props)
        if stamp:
            stamp_entity(entity_id)
    except Exception as exc:  # noqa: BLE001
        log.warning("could not record %s %s for %s: %s", scheme, code, entity_id, exc)
        return None
    return props


def statements_for(entity_id: str) -> list[dict]:
    from app.db.arcadedb import run_sql
    rows = run_sql(f"SELECT FROM {TYPE} WHERE entity_id = :e", {"e": entity_id})
    return sorted((dict(r) for r in rows), key=_statement_order)


def _statement_order(row: dict) -> tuple:
    scheme = row.get("scheme")
    rank = SCHEME_PRECEDENCE.index(scheme) if scheme in SCHEME_PRECEDENCE else len(SCHEME_PRECEDENCE)
    return (rank, row.get("position") or 1)


def principal(statements: list[dict]) -> dict | None:
    """The statement that decides the entity's tree: the first by scheme
    precedence and position that maps to a NACE node at all — a UK register's
    principal activity before a crosswalked SIC, a mapped code before a
    UK-only one that means nothing in NACE."""
    for row in sorted(statements, key=_statement_order):
        if row.get("nace_code"):
            return row
    return None


def stamp_entity(entity_id: str) -> str | None:
    """Set `Entity.nace_code` from the entity's statements. Returns the code."""
    from app.db.arcadedb import run_sql
    top = principal(statements_for(entity_id))
    code = top["nace_code"] if top else None
    run_sql("UPDATE Entity SET nace_code = :c WHERE id = :e", {"c": code, "e": entity_id})
    return code


def migrate(dead_id: str, keep_id: str) -> int:
    """Re-point the statements of a merged-away node at its survivor and
    re-key them (the key hashes the entity id). The survivor's own statement
    for the same scheme and position wins; the dead twin's is dropped."""
    from app.db.arcadedb import run_sql
    moved = 0
    kept = {(r.get("scheme"), r.get("position")) for r in statements_for(keep_id)}
    for row in statements_for(dead_id):
        slot = (row.get("scheme"), row.get("position"))
        run_sql(f"DELETE FROM {TYPE} WHERE key = :k", {"k": row.get("key")})
        if slot in kept:
            continue
        props = {k: v for k, v in row.items() if not k.startswith("@")}
        props["entity_id"] = keep_id
        props["key"] = statement_key(keep_id, row.get("scheme"), row.get("position") or 1)
        props.setdefault("last_seen_at", _now())
        run_sql(upsert_sql(props), props)
        moved += 1
    if moved:
        stamp_entity(keep_id)
    return moved


# ── Bulk: the UK register, and the backfill ─────────────────────────────────

CH_COMPANY_URL = "https://find-and-update.company-information.service.gov.uk/company/{number}"
SEC_COMPANY_URL = "https://www.sec.gov/cgi-bin/browse-edgar?action=getcompany&CIK={cik}"
_PAGE = 500


def ch_company_url(entity_id: str | None, companies_house_id: str | None) -> str | None:
    """The register's own page for a UK company: by its stored number, else the
    number in a `gb-coh:` id. None when neither is known — a link to
    `/company/` with nothing after it is a dead one."""
    number = (companies_house_id or "").strip()
    if not number and entity_id and entity_id.startswith("gb-coh:"):
        number = entity_id.split(":", 1)[1].strip()
    return CH_COMPANY_URL.format(number=number) if number else None


def _companies_house_source_id() -> str | None:
    from app.scraper.graph_writer import _ensure_source
    from app.scraper.sources import KNOWN_SOURCES
    src = KNOWN_SOURCES["bods_uk_psc"]
    return _ensure_source(src["label"], src["url"], src["credibility"])


def sync_uk_sic(entity_ids: list[str] | None = None, snapshot_date: str | None = None,
                source_id: str | None = None) -> int:
    """Turn the `uk_sic_codes` the BasicCompanyData import stored on UK
    companies into statements — one per position, dated by the snapshot —
    and stamp each company's `nace_code`. All UK companies carrying codes, or
    only `entity_ids` (the curated subset). Returns the statements written."""
    from app.db.arcadedb import run_sql, run_sqlscript
    source_id = source_id or _companies_house_source_id()
    if not source_id:
        return 0
    written = 0
    offset = 0
    while True:
        params: dict = {"skip": offset, "page": _PAGE}
        scope = ""
        if entity_ids is not None:
            if not entity_ids:
                break
            scope, params["ids"] = " AND id IN :ids", entity_ids
        rows = run_sql("SELECT id, companies_house_id, uk_sic_codes FROM Entity "
                       f"WHERE uk_sic_codes IS NOT NULL AND uk_sic_codes.size() > 0{scope} "
                       "ORDER BY id SKIP :skip LIMIT :page", params)
        if not rows:
            break
        stmts, sparams = [], {}
        for n, r in enumerate(rows):
            statements = []
            for pos, text in enumerate(r.get("uk_sic_codes") or [], start=1):
                parsed = parse_uk_sic(text)
                if not parsed:
                    continue
                props = statement_props(
                    r["id"], "uk-sic", parsed[0], parsed[1], source_id=source_id, position=pos,
                    source_url=ch_company_url(r["id"], r.get("companies_house_id")),
                    source_date=snapshot_date)
                statements.append(props)
                k = f"{n}_{pos}"
                sets = ", ".join(f"{name} = :{name}__{k}" for name in props)
                sparams.update({f"{name}__{k}": v for name, v in props.items()})
                stmts.append(f"UPDATE {TYPE} SET {sets}, first_seen_at = COALESCE(first_seen_at, :last_seen_at__{k}) "
                             f"UPSERT WHERE key = :key__{k};")
            top = principal(statements)
            sparams[f"nace__{n}"], sparams[f"eid__{n}"] = (top["nace_code"] if top else None), r["id"]
            stmts.append(f"UPDATE Entity SET nace_code = :nace__{n} WHERE id = :eid__{n};")
            written += len(statements)
        run_sqlscript("\n".join(stmts), sparams)
        if len(rows) < _PAGE:
            break
        offset += _PAGE
    return written


def backfill(limit: int | None = None, fetch=None) -> dict:
    """Give every company a sector its sources already know: SEC filers
    (`sec_cik`) without a US SIC statement get one from EDGAR; UK companies
    whose `uk_sic_codes` were stored but never turned into statements get
    those. Fill-only: a statement already recorded is not re-fetched."""
    from app.db.arcadedb import run_sql
    from app.scraper.sec_edgar import fetch_filer_sic
    from app.scraper.graph_writer import _ensure_source
    from app.scraper.sources import KNOWN_SOURCES

    sec = KNOWN_SOURCES["sec_edgar"]
    sec_source = _ensure_source(sec["label"], sec["url"], sec["credibility"])
    stated = {r["entity_id"] for r in run_sql(f"SELECT entity_id FROM {TYPE} WHERE scheme = 'us-sic'")}
    rows = [r for r in run_sql("SELECT id, name, sec_cik FROM Entity WHERE sec_cik IS NOT NULL")
            if r["id"] not in stated]
    if limit:
        rows = rows[:limit]
    filled: list[dict] = []
    for r in rows:
        sic = (fetch or fetch_filer_sic)(r["sec_cik"])
        if not sic:
            continue
        props = record(r["id"], "us-sic", sic[0], sic[1], source_id=sec_source,
                       source_url=SEC_COMPANY_URL.format(cik=r["sec_cik"]),
                       source_date=datetime.now(timezone.utc).date().isoformat())
        if props:
            filled.append({"id": r["id"], "name": r["name"], "code": sic[0], "nace": props["nace_code"]})

    uk_stated = {r["entity_id"] for r in run_sql(f"SELECT entity_id FROM {TYPE} WHERE scheme = 'uk-sic'")}
    uk_rows = [r["id"] for r in run_sql("SELECT id FROM Entity WHERE uk_sic_codes IS NOT NULL "
                                         "AND uk_sic_codes.size() > 0")
               if r["id"] not in uk_stated]
    uk_written = sync_uk_sic(entity_ids=uk_rows) if uk_rows else 0
    return {"sec_candidates": len(rows), "sec_filled": len(filled), "sec_changes": filled,
            "uk_companies": len(uk_rows), "uk_statements": uk_written}


# ── Readers ─────────────────────────────────────────────────────────────────

def profile_for(entity_id: str, nace_code: str | None = None,
                source_names: dict[str, str] | None = None) -> dict | None:
    """The full profile's `industry` block: the NACE tree the panel draws and
    the statements behind it — None when the entity has neither."""
    try:
        statements = statements_for(entity_id)
    except Exception as exc:  # noqa: BLE001
        log.warning("industry statements unreadable for %s: %s", entity_id, exc)
        statements = []
    top = principal(statements)
    code = (top or {}).get("nace_code") or nace_code
    tree = nace_tree(code)
    if not tree and not statements:
        return None
    names = source_names or {}
    return {
        "nace_code": code if tree else None,
        "tree": tree,
        "statements": [{
            "scheme": s.get("scheme"),
            "scheme_name": scheme_name(s.get("scheme")),
            "code": s.get("code"),
            "label": s.get("label"),
            "position": s.get("position"),
            "nace_code": s.get("nace_code"),
            "tree": nace_tree(s.get("nace_code")),    # its own path: the panel draws every branch
            "source_id": s.get("source_id"),
            "source_name": names.get(s.get("source_id")),
            "source_url": s.get("source_url"),
            "source_date": s.get("source_date"),
        } for s in statements],
    }
